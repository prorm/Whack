  assert.equal(await start.evaluate((action) => action.getBoundingClientRect().bottom + scrollY <= innerHeight), true,
    'The primary action fits in the first mobile viewport')
  await scan(page, 'Opportunity detail')
  await start.click()
  await h1(page, 'Learn to reconcile stock').waitFor()
  assert.equal(await btn(page, 'Extract worksheet facts').count(), 0)
  await btn(page, 'Visual').click()
  await page.getByText('128 − 132 = -4', { exact: true }).waitFor()
  await snap(page, 'mobile-lesson')
  await scan(page, 'Inventory lesson')
  await btn(page, 'Practice').click()
  await page.getByLabel('Expected closing stock').fill('132')
  await page.getByLabel('Signed stock difference').fill('4')
  await page.getByLabel('Signed stock difference').press('Enter')
  await h1(page, 'Recall the stock rule').waitFor()
  await btn(page, 'Go to recall question').click()
  const prompt = await page.locator('.reel-question').innerText()
  const [, counted, expected] = /Counted (\d+), expected (\d+)/.exec(prompt)
  await page.getByLabel('Your recall answer').fill(String(Number(counted) - Number(expected)))
  await page.getByLabel('Your recall answer').press('Enter')
  await btn(page, 'Start an unseen worksheet').click()
  await h1(page, 'Try an unseen worksheet').waitFor()
  await context.setOffline(true)
  await page.reload()
  await h1(page, 'Try an unseen worksheet').waitFor()
  const seed = await page.evaluate(() => JSON.parse(localStorage.getItem('scrollproof:journey:career-inventory-seed')))
  const key = stockResult(variant(seed))
