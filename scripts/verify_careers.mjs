  const page = observe(await context.newPage())
  await page.goto(base)
  await page.waitForFunction(() => navigator.serviceWorker.controller !== null)
  await snap(page, 'mobile-home')
  await scan(page, 'Mobile home')
  await page.getByRole('main').getByRole('link', { name: 'Explore roles', exact: true }).click()
  await h1(page, 'Explore roles').waitFor()
  await btn(page, 'Stock & inventory').click()
  assert.equal(await link(page, 'Dispatch & Payout Assistant').count(), 0)
  await btn(page, 'All roles').click()
